@st.cache_data(show_spinner=False)
def load_player_stats() -> pd.DataFrame:
    df = pd.read_csv(DATA_DIR / "player_stats.csv")
    df["position_group"] = df["position"].apply(_map_position_group)
    df["display_name"] = df["player_nickname"].fillna(df["player_name"])
    df = df[df["position"] != "0"]  # drop invalid rows
    return df

@st.cache_data(show_spinner=False)
def load_player_per90() -> pd.DataFrame:
    df = pd.read_csv(DATA_DIR / "player_per90.csv")
    df["display_name"] = df["player_nickname"].fillna(df["player_name"])
    df = df[df["position"] != "0"]
    return df

@st.cache_data(show_spinner=False)
def load_similarity_features() -> pd.DataFrame:
    return pd.read_csv(DATA_DIR / "similarity_features.csv").fillna(0)

@st.cache_data(show_spinner=False)
def load_clustered_features() -> pd.DataFrame:
    """
    Load or generate clustered player features.
    If the CSV is missing the required 'cluster' column it is rebuilt
    automatically from similarity_features.csv.
    """
    REQUIRED = {"player_id", "cluster", "pca_x", "pca_y", "tsne_x", "tsne_y"}
    cluster_path = DATA_DIR / "clustered_player_features.csv"
    if cluster_path.exists():
        df = pd.read_csv(cluster_path)
        if REQUIRED.issubset(set(df.columns)):
            return df
        # File exists but columns are wrong — fall through to rebuild
    return _build_clusters()


@st.cache_data(show_spinner=False)
def _build_clusters() -> pd.DataFrame:
    """Compute KMeans clusters + PCA + t-SNE from similarity features."""
    sim = load_similarity_features()
    X = sim[FEATURE_COLS_SIM].values

    km = KMeans(n_clusters=8, random_state=42, n_init=10)
    clusters = km.fit_predict(X)

    pca = PCA(n_components=2, random_state=42)
    pca_coords = pca.fit_transform(X)

    # Note: n_jobs not supported on all platforms — omit for portability
    tsne = TSNE(n_components=2, random_state=42, perplexity=30)
    tsne_coords = tsne.fit_transform(X)

    df = sim[["player_id", "player_name", "primary_position",
              "team_name", "competition_name"]].copy()
    df["cluster"] = clusters
    df["pca_x"]   = pca_coords[:, 0]
    df["pca_y"]   = pca_coords[:, 1]
    df["tsne_x"]  = tsne_coords[:, 0]
    df["tsne_y"]  = tsne_coords[:, 1]

    # Persist so next app restart skips this computation
    try:
        (DATA_DIR / "clustered_player_features.csv").write_text(
            df.to_csv(index=False), encoding="utf-8"
        )
    except Exception:
        pass  # Read-only FS (e.g. Streamlit Cloud) — silently skip
    return df

def _map_position_group(pos: str) -> str:
    for group, positions in POSITION_GROUPS.items():
        if pos in positions:
            return group
    return "Other"

