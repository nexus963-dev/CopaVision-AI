def _render_stats_table(p1_ps, p2_ps, p1_pp, p2_pp, p1_name, p2_name, pp_df):
    """Side-by-side stats table with winner highlighting."""
    metrics = [
        ("Goals", "goals", False), ("Assists", "assists", False),
        ("xG", "xg", False), ("xA", "xassists", False),
        ("Goals/90", "goals_per90", True), ("Assists/90", "assists_per90", True),
        ("xG/90", "xg_per90", True), ("Progressive Passes", "progressive_passes", False),
        ("Pass Accuracy %", "pass_accuracy", False),
        ("Dribbles Completed", "dribbles_completed", False),
        ("Tackles", "tackles", False), ("Interceptions", "interceptions", False),
        ("Pressures/90", "pressures_per90", True),
        ("Aerial Success %", "aerial_success_rate", False),
    ]
    rows = []
    for label, col, per90 in metrics:
        src1 = p1_pp if per90 else p1_ps
        src2 = p2_pp if per90 else p2_ps
        v1 = src1.get(col, np.nan); v2 = src2.get(col, np.nan)
        if pd.isna(v1) and pd.isna(v2): continue
        rows.append({"Metric": label,
                     p1_name: round(float(v1), 2) if not pd.isna(v1) else "—",
                     p2_name: round(float(v2), 2) if not pd.isna(v2) else "—"})
    if rows:
        tbl = pd.DataFrame(rows)
        st.dataframe(tbl.style.apply(
            lambda row: [
                "", 
                "background-color: rgba(0,255,157,0.12); color: #00ff9d;" if (
                    isinstance(row[p1_name], (int, float)) and
                    isinstance(row[p2_name], (int, float)) and
                    row[p1_name] > row[p2_name]) else "",
                "background-color: rgba(0,212,255,0.12); color: #00d4ff;" if (
                    isinstance(row[p1_name], (int, float)) and
                    isinstance(row[p2_name], (int, float)) and
                    row[p2_name] > row[p1_name]) else "",
            ], axis=1
        ), use_container_width=True, height=480)


