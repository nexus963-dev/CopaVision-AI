def make_radar(player_row: pd.Series, reference_row: pd.Series,
               player_name: str, ref_name: str,
               per90_df: pd.DataFrame) -> go.Figure:
    """Spider/radar chart comparing two players across metric groups."""
    labels, p_vals, r_vals = [], [], []

    for group, metrics in RADAR_METRICS.items():
        for m in metrics:
            col = m if m in per90_df.columns else None
            if col is None: continue
            labels.append(m.replace("_per90","").replace("_"," ").title())
            p_vals.append(percentile_rank(per90_df[col].dropna(), player_row.get(col, 0)))
            r_vals.append(percentile_rank(per90_df[col].dropna(), reference_row.get(col, 0)))

    fig = go.Figure()
    for name, vals, color, alpha in [
        (player_name, p_vals, COLORS["green"],  "33"),
        (ref_name,    r_vals, COLORS["accent"], "22"),
    ]:
        fig.add_trace(go.Scatterpolar(
            r=vals + [vals[0]], theta=labels + [labels[0]],
            fill="toself",
            fillcolor=color + alpha,
            line=dict(color=color, width=2),
            name=name,
            hovertemplate="<b>%{theta}</b><br>Percentile: %{r:.0f}<extra></extra>",
        ))

    fig.update_layout(
        **_PLOT_LAYOUT,
        polar=dict(
            bgcolor="rgba(14,22,33,0.6)",
            radialaxis=dict(visible=True, range=[0,100], showticklabels=False,
                            gridcolor=COLORS["border"]),
            angularaxis=dict(tickfont=dict(family="DM Sans", size=10, color=COLORS["text"]),
                             gridcolor=COLORS["border"]),
        ),
        legend=dict(font=dict(family="Barlow Condensed", color=COLORS["text"], size=13),
                    bgcolor="rgba(0,0,0,0)"),
        height=440, margin=dict(t=40, b=40, l=40, r=40),
    )
    return fig


def make_percentile_bars(player_row: pd.Series, per90_df: pd.DataFrame,
                          player_name: str) -> go.Figure:
    """Horizontal percentile bar chart for a single player."""
    metrics = {
        "Goals p90": "goals_per90", "Assists p90": "assists_per90",
        "xG p90": "xg_per90", "xA p90": "xassists_per90",
        "Prog. Passes p90": "progressive_passes_per90",
        "Dribbles p90": "dribbles_completed_per90",
        "Tackles p90": "tackles_per90", "Interceptions p90": "interceptions_per90",
        "Pressures p90": "pressures_per90", "Pass Accuracy": "pass_accuracy",
    }
    labels, pcts = [], []
    for label, col in metrics.items():
        if col in per90_df.columns and col in player_row.index:
            pct = percentile_rank(per90_df[col].dropna(), player_row.get(col, 0))
            labels.append(label); pcts.append(pct)

    colors = [get_percentile_color(p) for p in pcts]

    fig = go.Figure(go.Bar(
        x=pcts, y=labels, orientation="h",
        marker=dict(color=colors, line=dict(width=0)),
        text=[f"{p:.0f}th" for p in pcts], textposition="outside",
        textfont=dict(family="Barlow Condensed", size=12, color=COLORS["text"]),
        hovertemplate="<b>%{y}</b><br>Percentile: %{x:.0f}<extra></extra>",
    ))
    fig.update_layout(
        **_PLOT_LAYOUT,
        xaxis=dict(range=[0, 115], showgrid=False, visible=False),
        yaxis=dict(tickfont=dict(family="DM Sans", size=11, color=COLORS["text"])),
        height=380, margin=dict(t=10, b=10, l=10, r=60),
        title=dict(text=f"Percentile Rankings — {player_name}",
                   font=dict(family="Barlow Condensed", size=14, color=COLORS["text"])),
    )
    return fig


