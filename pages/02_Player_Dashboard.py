# SIMILAR PLAYER ENGINE
# ─────────────────────────────────────────────────────────────────────────────
def find_similar_players(player_id: int, sim_df: pd.DataFrame,
                          n: int = 10, same_pos_only: bool = False) -> pd.DataFrame:
    """Return top-N most similar players using cosine similarity."""
    idx = sim_df.index[sim_df["player_id"] == player_id]
    if len(idx) == 0:
        return pd.DataFrame()

    pos = sim_df.loc[idx[0], "primary_position"]
    X = sim_df[FEATURE_COLS_SIM].values
    query_vec = X[idx[0]].reshape(1, -1)
    sims = cosine_similarity(query_vec, X)[0]

    result = sim_df.copy()
    result["similarity"] = sims
    result = result[result["player_id"] != player_id]

    if same_pos_only:
        result = result[result["primary_position"] == pos]

    return result.nlargest(n, "similarity")[
        ["player_id","player_name","primary_position","team_name",
         "competition_name","similarity"]
    ].reset_index(drop=True)


